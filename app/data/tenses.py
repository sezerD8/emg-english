def tense_by_key(key: str) -> dict | None:
    return next((t for t in TENSES if t["key"] == key), None)


def widget_snippets() -> list[dict]:
    out = []
    for t in TENSES:
        formula = t["formula"]["positive"]
        for en, tr in t["examples"]:
            out.append({"kind": "tense", "key": t["key"], "title": f"{t['name']} — {t['tr']}",
                        "en": en, "tr": tr, "formula": formula})
    return out


def all_quiz_questions() -> list[tuple[dict, dict]]:
    return [(t, q) for t in TENSES for q in t["quiz"]]
